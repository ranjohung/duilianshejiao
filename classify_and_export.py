os.makedirs(OUT, exist_ok=True)

# ============ 第一步：去重 + 过滤 ============
all_files = {}
for fn in os.listdir(RAW):
    if not fn.endswith('.txt'):
        continue
    sz = os.path.getsize(os.path.join(RAW, fn))
    if sz < 200:  # 跳过安装说明
        continue
    # 去重：去掉 "(1)" 后缀，保留最大的那个
    clean_name = re.sub(r'\s*\(\d+\)\s*', '', fn)
    if clean_name not in all_files or sz > all_files[clean_name][1]:
        all_files[clean_name] = (fn, sz)

print(f"去重前: {sum(1 for f in os.listdir(RAW) if f.endswith('.txt'))}")
print(f"去重后: {len(all_files)}")


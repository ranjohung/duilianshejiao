def classify(filename):
    """返回 (目录名, 展示名)"""
    for cat_dir, cat_name, keywords in CATEGORY_RULES:
        for kw in keywords:
            if kw in filename:
                return cat_dir, cat_name
    return "99-其他", "其他"

# ============ 第三步：扫描分类 ============
classified = defaultdict(list)
for clean_name, (orig_name, sz) in sorted(all_files.items()):
    cat_dir, cat_name = classify(orig_name)
    classified[cat_dir].append((orig_name, sz, clean_name))

print("\n=== 分类结果 ===")
for cat_dir in sorted(classified.keys()):
    items = classified[cat_dir]
    total_kb = sum(sz for _, sz, _ in items) / 1024
    print(f"  {cat_dir}: {len(items)} 个文件, {total_kb:.1f} KB")
    for orig, sz, clean in items[:3]:
        print(f"      {sz/1024:7.1f} KB | {clean}")
    if len(items) > 3:
        print(f"      ... 还有 {len(items)-3} 个")
